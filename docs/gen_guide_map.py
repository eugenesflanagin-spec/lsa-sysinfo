#!/usr/bin/env python3
"""Map every LSA result item id to its section in the user guide, for lsa-gui's Guide links /
F1 and `lsa guide ITEM`.

The item ids are the table between GUIDE-ITEMS-BEGIN and GUIDE-ITEMS-END in guide.c. Each item
in docs/RESULTS.md is a "## Title" heading followed (after at most a blank line) by a line
"`id` - kind". The anchor is the id the guide build (build_lsa_pdf.py) gives that heading: the
file name, lower-cased with every non-alphanumeric run turned into "-", then "--", then the
GitHub-style heading id (pandoc -f gfm). The same id is a named destination in
LSA-User-Guide.pdf and an element id in html/LSA-User-Guide.html.

  python3 docs/gen_guide_map.py            write guide_map.inc, fail if an item has no section
  python3 docs/gen_guide_map.py --check    only check (guide_map.inc up to date, every item mapped)
Run from the repository root."""
import re
import sys
import unicodedata

DOCS = ["docs/RESULTS.md"]

def prefix(rel):
    return re.sub(r"[^a-z0-9]+", "-", rel.lower().removesuffix(".md")).strip("-")

def gfm_id(title, seen):
    # pandoc gfm_auto_identifiers: lower-case, drop punctuation except - and _, spaces -> -
    s = "".join(c for c in title.strip().lower()
                if c.isalnum() or c in "-_ " or unicodedata.category(c).startswith("L"))
    s = s.replace(" ", "-")
    base, n = s, 0
    while s in seen:
        n += 1
        s = "%s-%d" % (base, n)
    seen.add(s)
    return s

def doc_map():
    m = {}
    for path in DOCS:
        rel = path[len("docs/"):]
        seen = set()
        lines = open(path, encoding="utf-8").read().split("\n")
        for i, l in enumerate(lines):
            mh = re.match(r"^(#{1,6}) (.*?)\s*$", l)
            if not mh:
                continue
            hid = gfm_id(mh.group(2), seen)
            if mh.group(1) != "##":
                continue
            nxt = next((x for x in lines[i + 1:i + 4] if x.strip()), "")
            mi = re.match(r"^`([a-z0-9][a-z0-9._-]*)`", nxt)
            if mi and mi.group(1) not in m:
                m[mi.group(1)] = prefix(rel) + "--" + hid
    return m

def code_ids():
    src = open("guide.c", encoding="utf-8").read()
    block = src[src.index("GUIDE-ITEMS-BEGIN"):src.index("GUIDE-ITEMS-END")]
    return re.findall(r'\{\s*"([a-z0-9][a-z0-9._-]*)",\s*"', block)

def render(m):
    out = ["/* generated by docs/gen_guide_map.py from docs/RESULTS.md - do not edit */"]
    for k in sorted(m):
        out.append('{ "%s", "%s" },' % (k, m[k]))
    return "\n".join(out) + "\n"

m, ids = doc_map(), code_ids()
missing = [i for i in ids if i not in m]
text = render({k: v for k, v in m.items() if k in ids})
if missing:
    print("items without a guide section: " + " ".join(missing), file=sys.stderr)
if "--check" in sys.argv:
    try:
        cur = open("guide_map.inc", encoding="utf-8").read()
    except OSError:
        cur = ""
    if cur != text:
        print("guide_map.inc is out of date: run python3 docs/gen_guide_map.py", file=sys.stderr)
        sys.exit(1)
    if not missing:
        print("check-guide: all %d items have a guide section" % len(ids))
    sys.exit(1 if missing else 0)
open("guide_map.inc", "w", encoding="utf-8").write(text)
print("%d of %d items mapped -> guide_map.inc" % (len(ids) - len(missing), len(ids)))
sys.exit(1 if missing else 0)
